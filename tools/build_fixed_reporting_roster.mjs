import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import {reportingUnitKey, reportingTextKey} from '../src/reportingIdentity.js';

// Deliberate register revision only. Normal imports/builds must never grow it.
const root = new URL('../', import.meta.url);
const {tracerReportingPeriods: periods} = JSON.parse(fs.readFileSync(new URL('public/data/tracer/2026/oct.json', root), 'utf8'));
const evidence = ['2026-10-11', '2026-10-18', '2026-10-25'];
const selected = evidence.map(date => {
  const period = periods.find(p => p.id === date);
  if (!period) throw new Error(`Missing baseline evidence: ${date}`);
  return period;
});
const districts = selected[0].dataQuality.districts.map(({province, name}) => ({province, name}));
if (districts.length !== 116 || new Set(districts.map(d => `${d.province}|${d.name}`)).size !== 116) throw new Error('Expected 116 unique districts');
const directory = new Map(districts.map(d => [`${reportingTextKey(d.province)}|${reportingTextKey(d.name)}`, d]));
const units = new Map();
function add(row, date) {
  const district = directory.get(`${reportingTextKey(row.province)}|${reportingTextKey(row.district)}`);
  if (!district) throw new Error(`Unrecognised district: ${JSON.stringify(row)}`);
  const clean = {...row, province: district.province, district: district.name};
  const id = reportingUnitKey(clean);
  const previous = units.get(id);
  if (previous) {
    if (!previous.aliases.includes(row.name)) previous.aliases.push(row.name);
    if (date && !previous.evidencePeriods.includes(date)) previous.evidencePeriods.push(date);
    return;
  }
  units.set(id, {id, province: clean.province, district: clean.district, facilityLevel: row.facilityLevel,
    name: row.name, isAggregate: ['HEALTH CENTRE', 'HEALTH POST'].includes(row.facilityLevel),
    aliases: [row.name], evidencePeriods: date ? [date] : []});
}
for (const d of districts) for (const level of ['HEALTH CENTRE', 'HEALTH POST']) {
  add({province: d.province, district: d.name, facilityLevel: level,
    name: `${d.name} ${level === 'HEALTH CENTRE' ? 'Health Centre' : 'Health Post'} facilities`});
}
for (const p of selected) for (const row of [...p.facilities, ...p.dataQuality.facilities]) add(row, p.id);
const roster = {version: '2026-operational-v1', appliesFrom: '2026-01-01', appliesThrough: '2026-12-31',
  status: 'Operational baseline; pending administrative certification, not a physical-facility census',
  evidencePeriods: evidence, expectedDistricts: districts.length, expectedUnits: units.size,
  primaryCareStreams: 232, hospitalAndServiceUnits: units.size - 232, districts,
  units: [...units.values()].sort((a, b) => a.id.localeCompare(b.id))};
console.log(JSON.stringify({version: roster.version, expectedDistricts: 116, expectedUnits: units.size,
  primaryCareStreams: 232, hospitalAndServiceUnits: roster.hospitalAndServiceUnits}));
if (process.argv.includes('--write')) {
  fs.writeFileSync(fileURLToPath(new URL('src/reportingRoster2026.js', root)),
    `// Generated by tools/build_fixed_reporting_roster.mjs --write. Review before revising.\nexport default ${JSON.stringify(roster, null, 2)};\n`);
}
